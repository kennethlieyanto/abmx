use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};

use super::assets;

/// The two skills written by `abmx generate skill parser`.
pub const SKILL_IDS: [&str; 2] = ["abmx-parser-authoring", "abmx-parser-install"];

struct SkillFile {
    relative: &'static str,
    content: String,
}

/// Write the generated skill tree under `out`.
///
/// Files that already exist with different content are only replaced with
/// `force`, so a user's edits are never silently discarded.
pub fn write_skills(out: &Path, force: bool) -> Result<Vec<PathBuf>> {
    let mut written = Vec::new();

    for file in files() {
        let path = out.join(file.relative);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)
                .with_context(|| format!("creating {}", parent.display()))?;
        }

        if path.exists() && !force {
            let existing = std::fs::read_to_string(&path)
                .with_context(|| format!("reading {}", path.display()))?;
            if existing == file.content {
                written.push(path);
                continue;
            }
            bail!(
                "{} already exists and differs; pass --force to overwrite generated skills",
                path.display()
            );
        }

        std::fs::write(&path, &file.content)
            .with_context(|| format!("writing {}", path.display()))?;
        written.push(path);
    }

    Ok(written)
}

