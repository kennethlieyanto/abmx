use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

use clap::ValueEnum;

use super::assets;
use super::samples::{self, Sample, SampleSet};

/// How a parser id is chosen when the samples come from Gmail labels.
#[derive(Debug, Clone, Copy, PartialEq, Eq, ValueEnum)]
pub enum IdFrom {
    /// Derive the id from the label, e.g. `example/QRIS Payment` -> `example.qris_payment`.
    Label,
    /// Let the agent propose an id and confirm it with the user.
    Infer,
}

/// Everything the prompt needs about the user's installation.
pub struct PromptContext {
    pub config_path: Option<PathBuf>,
    pub corpus: PathBuf,
    pub draft_dir: PathBuf,
    /// The directory the samples were loaded from, when there is one.
    pub input: Option<PathBuf>,
    pub explicit_id: Option<String>,
    pub id_from: IdFrom,
    /// True when the samples came from Gmail labels.
    pub from_gmail: bool,
    pub summaries: Vec<txp::SpecSummary>,
    pub accounts: BTreeMap<String, String>,
    pub parser: Option<txp::Parser>,
}

pub fn render_prompt(set: &SampleSet, context: &PromptContext) -> String {
    debug_assert_eq!(assets::SPEC_REFERENCE_VERSION, txp::SPEC_VERSION);
    let mut out = String::new();

    header(&mut out, set, context);
    task(&mut out, context);
    questions(&mut out, context);
    evidence(&mut out, set, context);
    corpus(&mut out, context);
    out.push_str(assets::SPEC_REFERENCE);
    out.push('\n');
    out.push_str(assets::AUTHORING_WORKFLOW);
    out.push('\n');
    out.push_str(assets::PITFALLS);
    out.push('\n');
    deliverables(&mut out, context);
    out
}

fn header(out: &mut String, set: &SampleSet, context: &PromptContext) {
    let _ = writeln!(out, "# Task: author a txp parser");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "<!-- generated by txsync {} at {} -->",
        env!("CARGO_PKG_VERSION"),
        chrono::Utc::now().to_rfc3339()
    );
    let _ = writeln!(
        out,
        "<!-- txp spec_version {}; {} sample(s), {} failure(s) -->",
        txp::SPEC_VERSION,
        set.sample_count(),
        set.failures.len()
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "> **Privacy:** this prompt contains real transaction data. Prefer a local \
         model, or redact the samples before sending them anywhere."
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "You are writing [`txp`](https://github.com/kennethlieyanto/txp) parser specs. \
         A spec is one TOML data file; the parsing engine is fixed. Your job is to \
         identify the template(s) in the samples and fill in the labels, routing, and \
         extraction rules."
    );
    let _ = writeln!(out);
    match (&context.explicit_id, context.id_from) {
        (Some(id), _) => {
            let _ = writeln!(
                out,
                "The user supplied the parser id `{id}`. Use it only if the samples form \
                 one template; if they do not, report the conflict before writing."
            );
        }
        (None, IdFrom::Label) if context.from_gmail => {
            let _ = writeln!(
                out,
                "Derive parser ids from the Gmail labels (slugified). Split a label into \
                 suffixed ids only if it contains more than one template."
            );
        }
        (None, _) => {
            let _ = writeln!(
                out,
                "No parser id was supplied. Propose one from the sender, subject, and kind, \
                 and ask the user to confirm before writing the final file."
            );
        }
    }
    let _ = writeln!(out);
}

fn task(out: &mut String, context: &PromptContext) {
    let _ = writeln!(out, "## Your job");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "1. Read every block dump below. Blocks are the only thing a parser sees; \
         HTML tags and layout do not matter."
    );
    let _ = writeln!(
        out,
        "2. Decide how many **templates** are present. A template is a distinct block \
         shape and routing identity. Several templates can share a sender and subject."
    );
    let _ = writeln!(
        out,
        "3. Write one spec per template into the draft directory. Do not write into \
         the live corpus until the user confirms."
    );
    let _ = writeln!(
        out,
        "4. Verify every sample with `txsync verify parser`. A spec is not done until \
         every sample is `strict` (or you have a written reason why an exception is correct)."
    );
    let _ = writeln!(
        out,
        "5. Ask the user before choosing an account key, a ledger account mapping, or \
         an id you are unsure about."
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "### Stop rules");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "- If the samples contain no monetary amount, do not create a parser. Report why."
    );
    let _ = writeln!(
        out,
        "- If a sample already routes to an existing parser and extracts correctly, do \
         not create a duplicate. Report the existing id."
    );
    let _ = writeln!(
        out,
        "- Never invent a value, a ledger UUID, or an account mapping. A guess that \
         parses is worse than an omitted optional field."
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "### Environment");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "- txsync config: `{}`",
        context
            .config_path
            .as_ref()
            .map(|path| path.display().to_string())
            .unwrap_or_else(|| "(none found)".to_owned())
    );
    let _ = writeln!(out, "- install corpus: `{}`", context.corpus.display());
    let _ = writeln!(out, "- draft directory: `{}`", context.draft_dir.display());
    if let Some(input) = &context.input {
        let _ = writeln!(out, "- samples: `{}`", input.display());
    }
    let _ = writeln!(out);
}

fn questions(out: &mut String, context: &PromptContext) {
    let _ = writeln!(out, "## Questions you must ask the user");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "Ask these before you write a final spec or touch `txsync.toml`. If you cannot \
         ask interactively, stop and list the questions instead of guessing."
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "1. **Parser id.** Confirm each id when more than one template is present, or \
         when `--id-from=infer`/no explicit id was supplied."
    );
    let _ = writeln!(
        out,
        "2. **Account key.** `[defaults].account` is a parser-side key such as \
         `example-account`, not a ledger UUID. Reuse an existing key only if the samples \
         clearly belong to that account; otherwise propose a new key."
    );
    let _ = writeln!(
        out,
        "3. **Ledger mapping.** Run `txsync accounts --json` (or `txsync accounts`) to \
         show the sink's accounts, then ask which one this key maps to. Add the \
         `[accounts]` entry only with the user's answer."
    );
    let _ = writeln!(
        out,
        "4. **Installation.** Ask whether to copy the verified draft into `{}`.",
        context.corpus.display()
    );
    let _ = writeln!(out);
}

fn evidence(out: &mut String, set: &SampleSet, context: &PromptContext) {
    let _ = writeln!(out, "## Samples");
    let _ = writeln!(out);

    if set.groups.is_empty() {
        let _ = writeln!(
            out,
            "**No samples could be loaded.** Do not author a parser; report the failure."
        );
        let _ = writeln!(out);
    }

    for (index, group) in set.groups.iter().enumerate() {
        let title = group
            .label
            .as_deref()
            .map(|label| format!("label `{label}`"))
            .unwrap_or_else(|| "ungrouped samples".to_owned());
        let suggestion = group
            .label
            .as_deref()
            .filter(|_| context.from_gmail && context.id_from == IdFrom::Label)
            .map(samples::slug)
            .filter(|slug| !slug.is_empty());
        let _ = writeln!(
            out,
            "### Group {}: {title}{}",
            index + 1,
            suggestion
                .as_deref()
                .map(|id| format!(" (suggested id: `{id}`)"))
                .unwrap_or_default()
        );
        let _ = writeln!(out);
        let _ = writeln!(
            out,
            "{} sample(s). A label is a user hint that these share one structure, not \
             proof. If the shapes below disagree, say so and ask whether to split.",
            group.samples.len()
        );
        let _ = writeln!(out);

        let senders = samples::by_sender(&group.samples);
        if senders.len() > 1 {
            let _ = writeln!(
                out,
                "> **Warning:** this group contains {} senders. That usually means one \
                 label spans more than one bank/type. Consider one spec per sender.",
                senders.len()
            );
            let _ = writeln!(out);
        }

        for sender in &senders {
            let _ = writeln!(out, "#### Sender `{}`", sender.sender);
            let _ = writeln!(out);
            let _ = writeln!(out, "Subjects seen:");
            for subject in &sender.subjects {
                let _ = writeln!(out, "- `{subject}`");
            }
            let _ = writeln!(out);

            match samples::variance(
                &sender
                    .samples
                    .iter()
                    .map(|sample| (*sample).clone())
                    .collect::<Vec<_>>(),
            ) {
                Some(variance) if variance.same_shape => {
                    let single = sender.samples.len() == 1;
                    let _ = writeln!(
                        out,
                        "All {} sample(s) have **{} blocks**. Constant labels and varying \
                         values:",
                        sender.samples.len(),
                        variance.block_count
                    );
                    let _ = writeln!(out);
                    let _ = writeln!(out, "| idx | kind | distinct values |");
                    let _ = writeln!(out, "| --- | --- | --- |");
                    for row in &variance.rows {
                        let kind = if single {
                            "constant"
                        } else if row.label_like {
                            "label?"
                        } else if row.constant {
                            "constant"
                        } else {
                            "value"
                        };
                        let _ = writeln!(
                            out,
                            "| {} | {} | {} |",
                            row.index,
                            kind,
                            format_values(&row.values)
                        );
                    }
                    let _ = writeln!(out);
                    if single {
                        let _ = writeln!(
                            out,
                            "> Only one sample was supplied. A block is trivially constant in \
                             one sample, so this table cannot tell a label from a value. Add \
                             more samples before trusting `labels.list`."
                        );
                        let _ = writeln!(out);
                    } else if variance.all_constant() {
                        let _ = writeln!(
                            out,
                            "> Every block is constant across the samples. This looks like a \
                             notification, not a transaction. Confirm with the user before \
                             writing a spec."
                        );
                        let _ = writeln!(out);
                    } else {
                        let _ = writeln!(
                            out,
                            "> `label?` is a heuristic from length and wording. A constant \
                             value (a fixed merchant, a fixed fee) can look the same. Use the \
                             block order and the other samples to decide."
                        );
                        let _ = writeln!(out);
                    }
                }
                Some(variance) => {
                    let counts: Vec<String> = sender
                        .samples
                        .iter()
                        .map(|sample| sample.email.blocks.len().to_string())
                        .collect();
                    let _ = writeln!(
                        out,
                        "> **Shapes differ:** block counts are {}. These are probably \
                         different templates. Split them by a discriminating label and use \
                         `requires` / `rejects`, or ask the user whether the label is wrong.",
                        counts.join(", ")
                    );
                    let _ = writeln!(
                        out,
                        "> (First sample has {} blocks; inspect the dumps below.)",
                        variance.block_count
                    );
                    let _ = writeln!(out);
                }
                None => {}
            }

            for sample in &sender.samples {
                sample_dump(out, sample, context);
            }
        }
    }

    if !set.failures.is_empty() {
        let _ = writeln!(out, "### Samples that could not be normalized");
        let _ = writeln!(out);
        for failure in &set.failures {
            let _ = writeln!(out, "- `{}`: {}", failure.origin, failure.error);
        }
        let _ = writeln!(out);
    }

    if set.truncated > 0 {
        let _ = writeln!(
            out,
            "> {} additional sample(s) were omitted by `--max-samples`.",
            set.truncated
        );
        let _ = writeln!(out);
    }
}

fn sample_dump(out: &mut String, sample: &Sample, context: &PromptContext) {
    let _ = writeln!(out, "##### `{}`", sample.file_name);
    let _ = writeln!(out);
    let _ = writeln!(out, "- path: `{}`", sample.origin);
    let _ = writeln!(
        out,
        "- from: `{}` <{}>",
        sample.email.from.name.as_deref().unwrap_or(""),
        sample.email.from.email
    );
    let _ = writeln!(out, "- subject: `{}`", sample.email.subject);
    let _ = writeln!(out, "- date: `{}`", sample.email.date.to_rfc3339());
    let _ = writeln!(
        out,
        "- message-id: `{}`",
        sample.email.source.message_id.as_deref().unwrap_or("-")
    );

    if let Some(parser) = &context.parser {
        let route = parser.registry().route(&sample.email);
        let existing = route
            .parser
            .map(|index| {
                format!(
                    "`{}` ({})",
                    parser.registry().parsers[index].spec.id,
                    route.reason.as_str()
                )
            })
            .unwrap_or_else(|| format!("none ({})", route.reason.as_str()));
        let _ = writeln!(out, "- current corpus: {existing}");
    }

    let _ = writeln!(out, "- blocks ({}):", sample.email.blocks.len());
    let _ = writeln!(out);
    let _ = writeln!(out, "```text");
    for (index, block) in sample.email.blocks.iter().enumerate() {
        let _ = writeln!(out, "{index:>3}  {}", block.text);
    }
    let _ = writeln!(out, "```");
    let _ = writeln!(out);
}

fn format_values(values: &[String]) -> String {
    let shown: Vec<String> = values
        .iter()
        .take(5)
        .map(|value| {
            let escaped = value.replace('|', "\\|").replace('\n', " ");
            format!("`{}`", truncate(&escaped, 60))
        })
        .collect();
    let suffix = if values.len() > 5 {
        format!(" … ({} values)", values.len())
    } else {
        String::new()
    };
    format!("{}{}", shown.join(" · "), suffix)
}

fn truncate(value: &str, limit: usize) -> String {
    if value.chars().count() <= limit {
        return value.to_owned();
    }
    let shortened: String = value.chars().take(limit.saturating_sub(1)).collect();
    format!("{shortened}…")
}

fn corpus(out: &mut String, context: &PromptContext) {
    let _ = writeln!(out, "## Current parser corpus");
    let _ = writeln!(out);
    if context.summaries.is_empty() {
        let _ = writeln!(
            out,
            "The configured corpus is empty or could not be loaded. Write the new spec \
             as a standalone file; do not assume sibling parsers exist."
        );
    } else {
        let _ = writeln!(out, "| id | ver | account | senders | subject |");
        let _ = writeln!(out, "| --- | --- | --- | --- | --- |");
        for summary in &context.summaries {
            let _ = writeln!(
                out,
                "| `{}` | {} | `{}` | {} | `{}` |",
                summary.id,
                summary.version,
                summary.account,
                summary
                    .senders
                    .iter()
                    .map(|sender| format!("`{sender}`"))
                    .collect::<Vec<_>>()
                    .join("<br>"),
                summary.subject.replace('|', "\\|")
            );
        }
        let _ = writeln!(out);
        let _ = writeln!(
            out,
            "If a sample shares a sender with one of these, check whether the existing \
             parser should be repaired instead of creating a duplicate."
        );
    }
    let _ = writeln!(out);

    if !context.accounts.is_empty() {
        let _ = writeln!(out, "### Existing account keys");
        let _ = writeln!(out);
        let _ = writeln!(
            out,
            "These keys are already mapped in `[accounts]`. Reuse one only when the \
             samples belong to that account. Sink UUIDs are deliberately omitted; run \
             `txsync accounts --json` when you need them."
        );
        let _ = writeln!(out);
        for key in context.accounts.keys() {
            let _ = writeln!(out, "- `{key}`");
        }
        let _ = writeln!(out);
    }
}

fn deliverables(out: &mut String, context: &PromptContext) {
    let _ = writeln!(out, "## Deliverables");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "Write each spec to `{}` first. Then report:",
        context.draft_dir.display()
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "1. the template(s) you found and the chosen id(s);");
    let _ = writeln!(
        out,
        "2. the account key for each, and any mapping question;"
    );
    let _ = writeln!(out, "3. the exact verification commands and their output;");
    let _ = writeln!(out, "4. anything you could not extract and why.");
    let _ = writeln!(out);
    let _ = writeln!(out, "Verification loop:");
    let _ = writeln!(out);
    let _ = writeln!(out, "```sh");
    let _ = writeln!(
        out,
        "txsync verify parser <path-to-your-draft.toml> --input {}",
        context
            .input
            .as_ref()
            .map(|path| path.display().to_string())
            .unwrap_or_else(|| "<samples>".to_owned())
    );
    let _ = writeln!(
        out,
        "txsync dump <one-sample.eml>     # re-inspect blocks without txp installed"
    );
    let _ = writeln!(out, "```");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "If a spec still needs work after three verification passes, stop and report \
         what is ambiguous. Do not thrash."
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "After the user approves, copy each spec to `{}` and run `txsync parsers`, \
         `txsync doctor`, and `txsync sync --dry-run --from-dir <samples>`.",
        context.corpus.display()
    );
    let _ = writeln!(out);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn format_values_truncates_long_lists() {
        let values: Vec<String> = (0..9).map(|index| format!("value {index}")).collect();
        let rendered = format_values(&values);
        assert!(rendered.contains("value 0"));
        assert!(rendered.contains("(9 values)"));
    }
}
